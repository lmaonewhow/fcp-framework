// Actual Vue SFC compilation and isolated request/state tests; not browser E2E.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const { parse, compileScript, compileTemplate } = require(process.argv[2] || '@vue/compiler-sfc');
const ts = require(process.argv[3] || 'typescript');
const source = fs.readFileSync(path.join(root, 'integration/plus-ui/src/fcp/generator/GeneratorApply.vue'), 'utf8');
const { descriptor, errors } = parse(source);
assert.equal(errors.length, 0);
const script = compileScript(descriptor, { id: 'education-generator' });
assert.equal(compileTemplate({ source: descriptor.template.content, filename: 'GeneratorApply.vue', id: 'education-generator', compilerOptions: { bindingMetadata: script.bindings } }).errors.length, 0);
const js = ts.transpileModule(descriptor.scriptSetup.content.replace(/^import .*;$/gm, ''), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const profile = { profileId: 'education-p042-v1', version: 'reviewed-test-version', modules: ['foundation', 'roster'].map(module => ({ module, sourceId: `education:p042:${module}`, resources: [] })), inputDigests: { sql: 'test-digest' }, provenance: {} };
const ready = { planId: 'education-plan', applicable: true, files: [], conflicts: [], expiresAt: 'later' };
function harness(api, confirm = async () => {}) {
  const context = { api, AbortController, ref: value => ({ value }), computed: fn => ({ get value() { return fn(); } }), onBeforeUnmount: fn => { context.unmount = fn; }, defineExpose: () => {}, ElMessageBox: { confirm } };
  vm.createContext(context);
  vm.runInContext(js + ';globalThis.test={show,showEducation,changeModules,close,preview,apply,undo,refreshHistory,profile,educationMode,educationModules,plan,history,visible,busy,enabled,notice,workspace,fileLabel,unmount:globalThis.unmount};', context);
  return context.test;
}
const defaults = { getConfig: async () => ({ enabled: true, workspace: 'unit-workspace' }), getEducationProfile: async () => profile };
const tick = () => new Promise(resolve => setImmediate(resolve));
let count = 0, payload;
const a = harness({ ...defaults, createEducationPlan: async (...args) => { count++; payload = args; return ready; }, createPlan: () => { throw Error('generic route forbidden'); } });
await a.showEducation();
assert.equal(count, 0);
assert.equal(a.profile.value.version, 'reviewed-test-version');
a.educationModules.value = ['roster']; await a.preview();
assert.equal(count, 1); assert.equal(payload[0], 'reviewed-test-version'); assert.equal(JSON.stringify(payload[1]), '["roster"]');
assert.equal(a.plan.value.planId, 'education-plan');
a.educationModules.value = []; a.changeModules(); await a.preview();
assert.equal(a.plan.value, undefined); assert.equal(count, 1);
console.log('PASS reviewed profile version, explicit module selection, no generic endpoint, selection invalidates plan');
let finishProfile;
const b = harness({ ...defaults, getEducationProfile: () => new Promise(resolve => finishProfile = resolve), createPlan: async () => ready });
const opening = b.showEducation(); await tick(); b.close(); await b.show(['001']); finishProfile(profile); await opening;
assert.equal(b.educationMode.value, false); assert.equal(b.profile.value, undefined); assert.equal(b.plan.value.planId, ready.planId);
console.log('PASS cancelled profile response cannot contaminate reopened generic session');
const c = harness({ ...defaults, getEducationProfile: async () => { throw Error('403'); } });
await c.showEducation(); assert.equal(c.enabled.value, false); assert.equal(c.profile.value, undefined); assert.match(c.notice.value, /无法读取教育生成规则/);
console.log('PASS inaccessible education profile fails closed');
let finishPlan;
const d = harness({ ...defaults, createEducationPlan: () => new Promise(resolve => finishPlan = resolve) });
await d.showEducation(); const planning = d.preview(); d.close(); finishPlan(ready); await planning;
assert.equal(d.plan.value, undefined); assert.equal(d.visible.value, false);
console.log('PASS late education plan discarded after cancel');
let writes = 0, rollbackId;
const e = harness({ ...defaults, createEducationPlan: async () => ready, applyPlan: async () => { writes++; return { status: 'applied' }; }, getOperations: async () => ({ operations: [{ operationId: 'applied-education', status: 'applied' }] }), rollback: async id => { rollbackId = id; return { status: 'rolled_back' }; } });
await e.showEducation(); await e.preview(); await e.apply(); assert.equal(writes, 1); assert.equal(e.plan.value, undefined); assert.equal(e.history.value.length, 1);
await e.undo(e.history.value[0]); assert.equal(rollbackId, 'applied-education');
assert.equal(e.fileLabel('adopt_generated'), '登记已生成文件，不改源码');
assert.match(source, /currentPreviewTruncated/); assert.match(source, /candidatePreviewTruncated/); assert.match(source, /generator-truncated-warning/);
console.log('PASS education uses existing apply/history/rollback and explicit adoption/truncation labels');
let response = { code: 200, data: profile }, captured;
const transport = { exports: {}, require: () => ({ default: async options => { captured = options; return response; } }) };
vm.createContext(transport);
vm.runInContext(ts.transpileModule(fs.readFileSync(path.join(root, 'integration/plus-ui/src/fcp/generator/api.ts'), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText, transport);
assert.equal((await transport.exports.getEducationProfile()).version, profile.version);
assert.equal(captured.url, '/fcp/generator/profiles/education-p042-v1');
response = { code: 200, data: ready }; await transport.exports.createEducationPlan(profile.version, ['foundation']);
assert.equal(captured.url, '/fcp/generator/profiles/education-p042-v1/plans'); assert.equal(captured.method, 'post');
assert.equal(JSON.stringify(captured.data), JSON.stringify({ profileId: profile.profileId, version: profile.version, modules: ['foundation'] }));
assert.equal(captured.headers.repeatSubmit, false);
for (const malformed of [null, {}, { ...profile, version: '' }, { ...profile, profileId: 'other' }, { ...profile, modules: [profile.modules[0], profile.modules[0]] }, { ...profile, inputDigests: [] }]) {
  response = { code: 200, data: malformed }; await assert.rejects(transport.exports.getEducationProfile(), /不受支持/);
}
console.log('PASS actual profile API transport, reviewed version body and malformed contract rejection');
