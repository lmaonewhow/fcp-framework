class GenerationGuards(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)
        self.root = self.directory/'source'
        self.root.mkdir()
        self.write('.gitignore', b'reports/\nbuild/\n.fcp-generator/\n')
        for name in gate.SOURCE_INPUTS:
            self.write(name, ('synthetic guard input: ' + name).encode())
        for name in gate.RESOURCE_INPUTS:
            self.write('core/src/main/resources/'+name[len('classpath:'):], ('synthetic resource: '+name).encode())
        self.write('core/src/main/java/dev/fcp/generator/EducationSqlRenderer.java', b'// synthetic guard fixture, not renderer execution\n')
        for name in gate.TARGETS.values():
            self.write(name, ('synthetic tracked generated bytes: '+name).encode())
        self.write('integration/plus-ui/src/views/fcp/education/manual-hook.ts', b'preserved hand-written hook\n')
        subprocess.run(['git','init','--quiet',self.root],check=True)
        subprocess.run(['git','add','.'],cwd=self.root,check=True)
        subprocess.run(['git','-c','user.name=CI guard test','-c','user.email=guard@example.invalid','commit','--quiet','-m','Synthetic safety fixture'],cwd=self.root,check=True)
        self.outputs = {name: gate.sha256(self.root/name) for name in gate.TARGETS.values()}
        self.inputs = {name: gate.sha256(self.root/name) for name in gate.SOURCE_INPUTS}
        self.all_inputs = dict(self.inputs)
        self.all_inputs.update({name:gate.sha256(self.root/('core/src/main/resources/'+name[len('classpath:'):])) for name in gate.RESOURCE_INPUTS})
        self.manifest = dict(profileId=gate.PROFILE, version='1', workspaceInputDigests=self.inputs,
            inputDigests=self.all_inputs, outputDigests={name:self.outputs[target] for name,target in gate.TARGETS.items()},
            provenance=dict(outputTargets=gate.TARGETS))
        self.applied = copy.deepcopy(self.manifest)
        self.applied.update(plan=dict(planId='00000000-0000-0000-0000-000000000001', applicable=True, conflicts=[],
            files=[dict(path=name,candidateSha256=digest,currentSha256=None,status='create') for name,digest in self.outputs.items()]),
            receipt=dict(planId='00000000-0000-0000-0000-000000000001',operationId='00000000-0000-0000-0000-000000000002',status='applied',files=list(self.outputs)))

    def write(self, name, content):
        path=self.root/name
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_bytes(content)
        return path

    def prepared_report(self):
        value=dict(status='PASS',scope='REAL_P042_RENDERER_GUARDED_CREATE_IN_EXACT_COMMIT_CLONE',
                   sourceCommit=gate.git(self.root,'rev-parse','HEAD'),genuineCreateCount=10,
                   restoredTrackedSnapshot=True,cleanGeneratedSourceTree=True,outputDigests=self.outputs,
                   inputDigests=self.all_inputs,workspaceInputDigests=self.inputs,profileVersion='1',
                   rendererSourceSha256=gate.sha256(self.root/'core/src/main/java/dev/fcp/generator/EducationSqlRenderer.java'),
                   receipt=self.applied['receipt'])
        self.write((gate.OUTPUT/'prebuild.json').as_posix(),json.dumps(value).encode())
        self.write((gate.OUTPUT/'applied.json').as_posix(),json.dumps(self.applied).encode())
        return value

    def test_fixed_scope_is_ten_targets_without_manual_hooks_or_sql(self):
        self.assertEqual(len(gate.TARGETS),10)
        self.assertFalse(any(name.endswith('.sql') or 'hooks' in name for name in gate.TARGETS.values()))
        self.assertEqual(gate.validate_manifest(self.root,self.manifest),self.outputs)
        self.assertEqual(gate.verify_snapshot(self.root,self.outputs),self.outputs)

    def test_actual_clone_has_exact_commit_without_hardlinks(self):
        clone=gate.GeneratedClone.create(self.root,self.directory/'clone')
        name=next(iter(self.outputs))
        self.assertEqual(gate.git(clone.root,'rev-parse','HEAD'),gate.git(self.root,'rev-parse','HEAD'))
        self.assertNotEqual((self.root/name).stat().st_ino,(clone.root/name).stat().st_ino)
        clone.remove_verified_targets(self.outputs)
        self.assertTrue(all(not (clone.root/name).exists() for name in self.outputs))
        self.assertTrue(all((self.root/name).exists() for name in self.outputs))
        self.assertEqual((clone.root/'integration/plus-ui/src/views/fcp/education/manual-hook.ts').read_bytes(),b'preserved hand-written hook\n')

    def test_existing_destination_is_never_overwritten(self):
        destination=self.directory/'existing';destination.mkdir()
        (destination/'mine').write_text('keep')
        with self.assertRaisesRegex(ValueError,'new empty'):
            gate.GeneratedClone.create(self.root,destination)
        self.assertEqual((destination/'mine').read_text(),'keep')

    def test_dirty_source_clone_refuses_without_creating_destination(self):
        self.write('untracked-user-file.txt',b'user draft')
        destination=self.directory/'clone'
        with self.assertRaisesRegex(ValueError,'source changes'):
            gate.GeneratedClone.create(self.root,destination)
        self.assertFalse(destination.exists())

    def test_complete_batch_verifies_before_any_delete(self):
        clone=gate.GeneratedClone.create(self.root,self.directory/'clone')
        wrong=dict(self.outputs);wrong[sorted(wrong)[-1]]='0'*64
        with self.assertRaisesRegex(ValueError,'snapshot differs'):
            clone.remove_verified_targets(wrong)
        self.assertTrue(all((clone.root/name).exists() for name in self.outputs))

    def test_source_or_commit_drift_prevents_removal(self):
        clone=gate.GeneratedClone.create(self.root,self.directory/'clone')
        name=next(iter(self.outputs))
        (clone.root/name).write_bytes(b'later user edit')
        with self.assertRaisesRegex(ValueError,'source changes'):
            clone.remove_verified_targets(self.outputs)
        self.assertTrue(all((clone.root/name).exists() for name in self.outputs))

    def test_path_escape_links_and_hardlinks_refused(self):
        for relative in ('../outside','/tmp/file','x//y','x/./y','x\\y','classpath:x','x\ny'):
            with self.subTest(relative=relative),self.assertRaises(ValueError):
                gate.safe_file(self.root,relative,must_exist=False)
        (self.root/'linked').symlink_to(self.directory,target_is_directory=True)
        with self.assertRaises(ValueError):gate.safe_file(self.root,'linked/file',must_exist=False)
        path=self.write('hard-link-original',b'keep')
        os.link(path,self.root/'hard-link-second')
        with self.assertRaisesRegex(ValueError,'single-link'):gate.safe_file(self.root,'hard-link-original')

    def test_manifest_unknown_or_missing_paths_refuse(self):
        for key in ('outputDigests','workspaceInputDigests','inputDigests'):
            value=copy.deepcopy(self.manifest);value[key].pop(next(iter(value[key])))
            with self.subTest(key=key),self.assertRaises(ValueError):gate.validate_manifest(self.root,value)
        value=copy.deepcopy(self.manifest);value['provenance']['outputTargets'][next(iter(gate.TARGETS))]='tools/native.py'
        with self.assertRaisesRegex(ValueError,'mapping'):gate.validate_manifest(self.root,value)

    def test_actual_input_or_classpath_drift_refuses(self):
        for name in (next(iter(gate.SOURCE_INPUTS)), 'core/src/main/resources/education-generator/rules.json'):
            path=self.root/name;old=path.read_bytes();path.write_bytes(old+b'new')
            with self.subTest(name=name),self.assertRaisesRegex(ValueError,'differs'):
                gate.validate_manifest(self.root,self.manifest)
            path.write_bytes(old)

    def test_manifest_duplicate_json_keys_refused(self):
        path=self.write('duplicate.json',b'{"status":"FAIL","status":"PASS"}')
        with self.assertRaisesRegex(ValueError,'Duplicate'):gate.read_json(path)

    def test_application_requires_create_not_noop_or_adopt(self):
        self.assertEqual(gate.verify_create_receipt(self.applied,self.outputs),self.applied['receipt'])
        for status in ('unchanged','adopt_generated','preserve_manual','update'):
            value=copy.deepcopy(self.applied);value['plan']['files'][0]['status']=status
            with self.subTest(status=status),self.assertRaisesRegex(ValueError,'genuine source CREATE'):
                gate.verify_create_receipt(value,self.outputs)

    def test_application_receipt_requires_exact_operation_scope(self):
        for field,value in [('status','noop'),('planId','other'),('operationId','not-an-operation'),('files',[])]:
            changed=copy.deepcopy(self.applied);changed['receipt'][field]=value
            with self.subTest(field=field),self.assertRaisesRegex(ValueError,'receipt'):
                gate.verify_create_receipt(changed,self.outputs)

    def test_prebuild_reader_validates_actual_receipt_and_all_hashes(self):
        expected=self.prepared_report()
        self.assertEqual(gate.validate_prebuild_report(self.root),expected)
        changed=copy.deepcopy(self.applied);changed['receipt']['status']='noop'
        self.write((gate.OUTPUT/'applied.json').as_posix(),json.dumps(changed).encode())
        with self.assertRaisesRegex(ValueError,'receipt'):gate.validate_prebuild_report(self.root)

    def test_prebuild_reader_refuses_wrong_head_or_false_completion(self):
        for field,value in [('status','FAIL'),('sourceCommit','0'*40),('genuineCreateCount',0),('cleanGeneratedSourceTree',False)]:
            report=self.prepared_report();report[field]=value
            self.write((gate.OUTPUT/'prebuild.json').as_posix(),json.dumps(report).encode())
            with self.subTest(field=field),self.assertRaisesRegex(ValueError,'receipt required'):
                gate.validate_prebuild_report(self.root)

    def test_native_run_is_gated_before_subprocess_and_has_no_business_flag(self):
        with patch.dict(os.environ,{'GITHUB_ACTIONS':'false'}),patch.object(subprocess,'run') as run,self.assertRaises(ValueError):
            gate.run_native(self.root)
        run.assert_not_called()
        self.assertNotIn('--generator-business',gate.NATIVE_FLAGS)
        self.assertEqual(set(gate.NATIVE_FLAGS),{'--ingestion','--education','--roster','--generator','--education-generator'})

    def test_native_run_requires_this_clones_component_class(self):
        self.prepared_report()
        with patch.dict(os.environ,{'GITHUB_ACTIONS':'true'}),self.assertRaisesRegex(ValueError,'component verification'):
            gate.run_native(self.root)

    def test_full_login_window_is_observed_without_reset(self):
        with patch.object(time,'sleep') as sleep,patch.object(time,'monotonic',side_effect=[10,70.02]):
            result=native.wait_login_window()
        sleep.assert_called_once_with(60)
        self.assertEqual(result,dict(stage='education-generator',waitSeconds=60.02,nativeRateLimitChanged=False))
        with patch.object(time,'sleep'),patch.object(time,'monotonic',side_effect=[10,69.99]),self.assertRaises(RuntimeError):
            native.wait_login_window()

    def test_native_fixture_copy_is_delayed_until_generic_generator_passes(self):
        class Host:
            database='fcp_ci_012345abcdef'
            private_dir=self.directory/'private'
        class Fixture:
            fixture=Host()
            root=Host.private_dir/'generator-source'
            report={'status':'NOT_RUN'}
        Fixture.root.mkdir(parents=True)
        value=dict(workspaceInputDigests=self.inputs,outputDigests=self.outputs)
        with patch.dict(os.environ,{'GITHUB_ACTIONS':'true'}),self.assertRaisesRegex(ValueError,'Completed ordinary'):
            native.initialize_workspace(Fixture,value,source=self.root)
        self.assertFalse((Fixture.root/'integration').exists())
        Fixture.report['status']='PASS'
        with patch.dict(os.environ,{'GITHUB_ACTIONS':'true'}):
            destination=native.initialize_workspace(Fixture,value,source=self.root)
        self.assertEqual(native.file_digests(destination,self.outputs),self.outputs)
        with patch.dict(os.environ,{'GITHUB_ACTIONS':'true'}),self.assertRaisesRegex(ValueError,'overwrite'):
            native.initialize_workspace(Fixture,value,source=self.root)

    def test_command_timeout_preserves_partial_log_without_fabricated_exit_code(self):
        output=self.directory/'log';output.mkdir();report={}
        with patch.object(subprocess,'run',side_effect=subprocess.TimeoutExpired('javac',1,output=b'partial compile')):
            with self.assertRaises(RuntimeError):gate.run_command(['javac'],self.root,output,'compile',report,timeout=1)
        self.assertEqual(report['commands'][0]['status'],'TIMEOUT')
        self.assertIsNone(report['commands'][0]['exitCode'])
        self.assertEqual((output/'compile.log').read_bytes(),b'partial compile')

    def test_missing_executable_is_blocked_and_keeps_command_evidence(self):
        output=self.directory/'log';output.mkdir();report={}
        with patch.object(subprocess,'run',side_effect=FileNotFoundError('not in PATH')):
            with self.assertRaises(gate.PrerequisiteError):gate.run_command(['javac'],self.root,output,'compile',report)
        self.assertEqual(report['commands'][0]['status'],'BLOCKED')
        self.assertIsNone(report['commands'][0]['exitCode'])
        self.assertNotIn('not in PATH',(output/'compile.log').read_text())

    def test_native_test_has_no_response_doubles_fullpage_or_permission_shortcuts(self):
        text=(ROOT/'tests/education_codegen/native_acceptance.py').read_text()
        for forbidden in ('page.route(', 'route.fulfill(', 'full_page=True', 'FLUSHALL', 'FLUSHDB', 'add_style_tag(', 'force=True'):
            self.assertNotIn(forbidden,text)
        self.assertEqual(native.VIEWPORT,dict(width=1440,height=1080))
        self.assertIn("educationChangedTemplateConflict='NOT_RUN_FIXED_CLASSPATH_TEMPLATES'",text)


