ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools'))
import ci_education_codegen as gate

spec = importlib.util.spec_from_file_location('education_codegen_native_test_subject', ROOT/'tests/education_codegen/native_acceptance.py')
native = importlib.util.module_from_spec(spec)
