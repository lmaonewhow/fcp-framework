"""Allowlist reference serializer; call BEFORE local disk, stdout, or queue.
This does not sanitize third-party agents, arbitrary stack traces or core dumps.
"""
from datetime import datetime, timezone
import re
from typing import Any

SERVER_EVENTS=frozenset({'command.committed','command.denied','command.unknown','plugin.failed','rollout.paused','queue.dropped'})
BROWSER_EVENTS=frozenset({'page.ready','resource.failed','action.failed','action.confirmed'})
ERROR_CODES=frozenset({'OK','DENIED','VALIDATION','TIMEOUT','INTERNAL','RESOURCE_LOAD','CONTRACT_UNSUPPORTED'})
HEX32=re.compile(r'^[0-9a-f]{32}$')
HEX64=re.compile(r'^[0-9a-f]{64}$')
UUID=re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')

class TelemetryRejected(ValueError):pass

def safe_event(raw: dict[str,Any], trusted: dict[str,Any], origin='server'):
    if origin not in ('server','browser') or not isinstance(raw,dict) or not isinstance(trusted,dict):raise TelemetryRejected('INVALID_INPUT')
    allowed=BROWSER_EVENTS if origin=='browser' else SERVER_EVENTS
    event=raw.get('event');code=raw.get('error_code','OK')
    if not isinstance(event,str) or event not in allowed or not isinstance(code,str) or code not in ERROR_CODES:raise TelemetryRejected('UNKNOWN_EVENT')
    # tenant pseudonym is generated by the trusted ingest service, never copied from the browser.
    tenant=trusted.get('tenant_ref');release=trusted.get('manifest_digest')
    if not isinstance(tenant,str) or not HEX64.fullmatch(tenant) or not isinstance(release,str) or not HEX64.fullmatch(release):raise TelemetryRejected('INVALID_TRUSTED_IDENTITY')
    out={'schema':'telemetry-v1','event':event,'error_code':code,'tenant_ref':tenant,'actual_manifest_digest':release,'origin':origin,'observed_at':datetime.now(timezone.utc).isoformat()}
    for field in ('operation_id','request_attempt_id'):
        v=trusted.get(field)
        if v is not None:
            if not isinstance(v,str) or not UUID.fullmatch(v):raise TelemetryRejected('INVALID_TRUSTED_CORRELATION')
            out[field]=v
    trace=trusted.get('trace_id')
    if trace is not None:
        if not isinstance(trace,str) or not HEX32.fullmatch(trace) or int(trace,16)==0:raise TelemetryRejected('INVALID_TRACE')
        out['trace_id']=trace
    duration=raw.get('duration_ms')
    if duration is not None:
        if type(duration) not in (int,float) or not 0<=duration<=86400000:raise TelemetryRejected('INVALID_DURATION')
        out['duration_ms']=duration
    if origin=='browser':
        v=raw.get('claimed_frontend_digest')
        if v is not None:
            if not isinstance(v,str) or not HEX64.fullmatch(v):raise TelemetryRejected('INVALID_CLAIM')
            out['claimed_frontend_digest']=v
        out['authoritative_business_result']=False
    # No free-text messages, paths, URLs, names, tokens, request bodies, raw SQL or exception text.
    return out
