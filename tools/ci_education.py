def schema_plan(database: str) -> dict:
    if os.environ.get('GITHUB_ACTIONS') != 'true' or not re.fullmatch(r'fcp_ci_[a-f0-9]{12}', database):
        raise ValueError('Only this run\'s newly created disposable CI database is permitted')
    sys.path.insert(0,str(ROOT))
    from runtime.education_contracts.catalog import load_catalog
    load_catalog(ROOT)  # Includes pinned source and generated catalog consistency checks.
    extension_lock=json.loads((ROOT/'contracts/education/foundation-sources.lock.json').read_text())
    expected_extension_paths={p.relative_to(ROOT).as_posix() for p in (EXTENSION,MENU)}
    if extension_lock.get('format')!=2 or set(extension_lock.get('sha256',{}))!=expected_extension_paths:
        raise ValueError('Invalid foundation extension source lock')
    for path in (EXTENSION,MENU):
        if hashlib.sha256(path.read_bytes()).hexdigest()!=extension_lock['sha256'][path.relative_to(ROOT).as_posix()]:
            raise ValueError('Foundation extension differs from reviewed source lock')
    sources = []
    for path in (P042, EXTENSION, MENU):
        content = path.read_bytes()  # Missing implementation is blocking, never silently skipped.
        sources.append({'path': path.relative_to(ROOT).as_posix(),
                        'sha256': hashlib.sha256(content).hexdigest()})
    value = {'database': database, 'purpose': 'fresh-native-education-composition',
             'sources': sources, 'expectedExtension': extension_lock['objects'], 'expectedMenus': extension_lock['menus'], 'existingDatabaseMigration': False}
    value['approvalDigest'] = hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()
    return value


def prepare(database: str, ddl_sql, *, creation_receipt: dict, approved_digest: str,
            output: Path, runtime_user: str) -> dict:
    """Run before application build/start, only after explicit fresh schema plan review.

    ddl_sql executes with a dedicated fcpe_* DDL user restricted to this schema and
    returns mysql --batch --skip-column-names text. It must not use the runtime user.
    creation_receipt is generated by the orchestrator immediately when it creates
    this schema from empty, before installing the planned pinned native schema.
    """
    plan = schema_plan(database)
    if approved_digest != plan['approvalDigest']:
        raise ValueError('The exact education DDL plan must be approved')
    if (creation_receipt.get('database') != database
            or creation_receipt.get('createdThisRun') is not True
            or creation_receipt.get('initialTableCount') != 0
            or not re.fullmatch(r'[a-f0-9]{32}', str(creation_receipt.get('runId', '')))):
        raise ValueError('Missing current-run empty-schema ownership evidence')
    output.mkdir(parents=True, exist_ok=False)
    (output/'plan.json').write_text(json.dumps(plan, indent=2)+'\n')
    state = {'status': 'RUNNING', 'completed': False, 'runId': creation_receipt['runId'],
             'database': database, 'scope': 'FRESH_ISOLATED_DDL_ONLY', 'nativeBusiness': 'NOT_RUN'}
    def save():
        temp=output/'result.tmp';temp.write_text(json.dumps(state, indent=2)+'\n');temp.replace(output/'result.json')
    save()
    try:
        deployment = ddl_sql('SELECT CURRENT_USER();').strip()
        if (not re.fullmatch(r'fcpe_[a-f0-9]{12}@[^\s]+', deployment)
                or deployment.split('@',1)[0] == runtime_user):
            raise ValueError('A dedicated schema-restricted fcpe_* DDL identity is required')
        names=ddl_sql(f"SELECT table_name FROM information_schema.tables WHERE table_schema='{database}' ORDER BY table_name;").splitlines()
        if not names or any(name.startswith('ed_') for name in names):
            raise ValueError('Pinned native schema must exist and no education table may already exist')
        # A structural backup of this disposable synthetic schema accompanies the original
        # empty-schema receipt. Never use this as a backup/recovery claim for user data.
        backup=[]
        for name in names:
            if not re.fullmatch('[A-Za-z0-9_]+',name):raise ValueError('Unexpected schema object')
            backup.append(ddl_sql(f'SHOW CREATE TABLE `{database}`.`{name}`;'))
        (output/'pre-education-schema.txt').write_text('\n'.join(backup))
        (output/'creation-receipt.json').write_text(json.dumps(creation_receipt,indent=2)+'\n')
        for source in plan['sources']:
            text=(ROOT/source['path']).read_text()
            if hashlib.sha256(text.encode()).hexdigest()!=source['sha256']:raise ValueError('DDL changed after approval')
            ddl_sql(f'USE `{database}`;\n'+text)
        model=json.loads((ROOT/'design/education-platform/v4.2.1/database/model.json').read_text())
        expected_columns={t['name']:{c['name'] for c in t['columns']} for t in model['tables']}
        expected_columns.update({t['name']:set(t['columns']) for t in plan['expectedExtension']})
        actual_names=set(ddl_sql(f"SELECT table_name FROM information_schema.tables WHERE table_schema='{database}' AND LEFT(table_name,3)='ed_' ORDER BY table_name;").splitlines())
        if actual_names!=set(expected_columns):raise ValueError('Education table set differs from locked model and extension')
        for table,columns in expected_columns.items():
            actual=set(ddl_sql(f"SELECT column_name FROM information_schema.columns WHERE table_schema='{database}' AND table_name='{table}' ORDER BY ordinal_position;").splitlines())
            if actual!=columns:raise ValueError('Education column set mismatch: '+table)
        expected_counts={'PRIMARY KEY':len(expected_columns),
                         'FOREIGN KEY':sum(len(t['foreign_keys']) for t in model['tables']),
                         'CHECK':sum(len(t['checks']) for t in model['tables'])+sum(t['checkCount'] for t in plan['expectedExtension']),
                         'UNIQUE':sum(len(t['unique']) for t in model['tables'])}
        for kind,expected in expected_counts.items():
            actual=ddl_sql(f"SELECT COUNT(*) FROM information_schema.table_constraints WHERE constraint_schema='{database}' AND LEFT(table_name,3)='ed_' AND constraint_type='{kind}';").strip()
            if actual!=str(expected):raise ValueError('Education constraint count mismatch: '+kind)
        menu_ids=','.join(str(item['id']) for item in plan['expectedMenus'])
        for item in plan['expectedMenus']:
            actual=ddl_sql(f"SELECT CONCAT(menu_id,'|',parent_id,'|',IFNULL(component,''),'|',perms,'|',is_cache,'|',status) FROM `{database}`.sys_menu WHERE menu_id={item['id']};").strip()
            expected='|'.join(str(item[k]) for k in ('id','parentId','component','permission','isCache','status'))
            if actual!=expected:raise ValueError('Education menu differs from reviewed plan')
        role_count=ddl_sql(f"SELECT COUNT(*) FROM `{database}`.sys_role_menu WHERE menu_id IN ({menu_ids});").strip()
        if role_count!='0':raise ValueError('Installation must not grant education menus to any role')
        state.update(status='PASS_DDL_ONLY',educationTableCount=len(actual_names),constraintCounts=expected_counts,menuCount=len(plan['expectedMenus']),

                     backupSha256=hashlib.sha256((output/'pre-education-schema.txt').read_bytes()).hexdigest())
    except BaseException as failure:
        state.update(status='FAIL',errorType=type(failure).__name__)
        raise
    finally:
        state['completed']=True;save()
    return state


class EducationPlan:
    def __init__(self, database, root_sql, output, receipt, plan):
        self.database,self.root_sql,self.output,self.receipt,self.plan=database,root_sql,output,receipt,plan
        self.applied=False
    def apply(self, ddl_sql, runtime_user, expected_host_tables):
        actual=set(self.root_sql(f"SELECT table_name FROM information_schema.tables WHERE table_schema='{self.database}' ORDER BY table_name;").splitlines())
        expected=set(expected_host_tables)
        if not expected or actual != expected or any(n.startswith('ed_') for n in actual):
            raise ValueError('Host schema does not exactly match the approved pinned host table plan')
        result=prepare(self.database,ddl_sql,creation_receipt=self.receipt,
                       approved_digest=self.plan['approvalDigest'],output=self.output/'apply',runtime_user=runtime_user)
        self.applied=True
        return result


def prepare_schema(database, root_sql, private_dir, output):
    """Call immediately after CREATE DATABASE, before mysql_install. Does not execute DDL."""
    plan=schema_plan(database)
    count=root_sql(f"SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='{database}';").strip()
    exists=root_sql(f"SELECT COUNT(*) FROM information_schema.schemata WHERE schema_name='{database}';").strip()
    if count!='0' or exists!='1':raise ValueError('Education composition requires a newly created empty schema')
    output=Path(output);output.mkdir(parents=True,exist_ok=False)
    receipt={'database':database,'createdThisRun':True,'initialTableCount':0,'runId':uuid.uuid4().hex}
    (output/'empty-schema-backup.json').write_text(json.dumps(receipt,indent=2)+'\n')
    (output/'composition-plan.json').write_text(json.dumps(plan,indent=2)+'\n')
    return EducationPlan(database,root_sql,output,receipt,plan)


